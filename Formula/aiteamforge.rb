  license "MIT"

  head "https://github.com/DoubleNode/homebrew-aiteamforge.git", branch: "main"

  # Core dependencies required for aiteamforge to function
  depends_on "gh"
  depends_on "git"
  depends_on "jq"
  depends_on macos: :big_sur # iTerm2 and macOS-specific features
  depends_on "node"
