'use strict';
/**
 * One-time (or deliberate re-run) generator for the XACA-1110-004 golden
 * dashboard-render baseline. NOT part of the automated `npm test` run --
 * invoke manually:
 *
 *   node tests/scripts/generate-xaca-1110-004-dashboard-baseline.js
 *
 * Captures full serialized DOM (via jsdom, real .innerHTML) for the 16-
 * fixture x collapsed/expanded machines matrix, the empty-state renders,
 * the populated-divisions render, and the getDivisionPriority() battery --
 * across the FOUR CURRENT lcars2 dashboard app files, before XACA-1110-005/
 * -009 unify them into one config-parameterized module.
 *
 * Uses the exact same matrix/capture/serialize code
 * (tests/helpers/lcars-fleet-dashboard-matrix.js) that the differential
 * harness test replays every run, so the baseline and the replay can never
 * drift apart by using two hand-written copies of the same logic -- same
 * split as generate-xaca-0990-001-baseline.js.
 *
 * THIS IS A DIFFERENT ARTIFACT FROM xaca-0990-001-lcars-terminal-card-
 * baseline.json. That file is pinned by the XACA-1110 design decision doc
 * (D8) and MUST NOT be regenerated by this ticket -- see the differential
 * harness test file's own "golden-baseline rule" section, which asserts
 * against xaca-0990-001's EXISTING content read-only. This generator only
 * ever writes xaca-1110-004-dashboard-render-baseline.json, a new artifact
 * this subitem introduces.
 *
 * Only re-run this deliberately (e.g. once XACA-1110-005/-009 unify the
 * four files AND that unification is proven behavior-preserving by every
 * OTHER assertion in the differential harness) -- regenerating it to make a
 * failing test pass defeats the whole point of a characterization baseline.
 */
const fs = require('node:fs');
const path = require('node:path');
const { computeAllResults, stableStringify } = require('../helpers/lcars-fleet-dashboard-matrix.js');

const OUT_PATH = path.join(__dirname, '..', 'xaca-1110-004-dashboard-render-baseline.json');

computeAllResults().then((results) => {
    const json = stableStringify(results);
    fs.writeFileSync(OUT_PATH, json, 'utf8');
    console.log('Wrote baseline to ' + OUT_PATH + ' (' + json.length + ' bytes)');
}).catch((err) => {
    console.error('Failed to generate baseline:', err);
    process.exit(1);
});
